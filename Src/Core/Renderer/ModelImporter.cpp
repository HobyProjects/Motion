    /**
     * @brief Return a path that is not already taken by a file or directory.
     * @param originalPath The path to check for availability.
     * @return A path that is not already taken by a file or directory.
     * 
     * This function takes a path and checks if a file or directory with the same name
     * already exists. If it does, it appends "-copy" followed by a number (starting at 1)
     * to the stem of the path. It continues to increment the number until it finds a name that is
     * not already taken.
     */
    static std::filesystem::path GetAvailableCopyName(const std::filesystem::path& originalPath)
    {
        if (!std::filesystem::exists(originalPath))
            return originalPath;

        std::filesystem::path directory = originalPath.parent_path();
        std::string stem = originalPath.stem().string();
        std::string extension = originalPath.extension().string();

        int counter = 1;
        std::filesystem::path newPath;

        do
        {
            newPath = directory / (stem + "-copy" + (counter > 1 ? std::to_string(counter) : "") + extension);
            ++counter;
        } while (std::filesystem::exists(newPath));

        return newPath;
    }

    /**
     * @brief Generates box projection UVs for a given set of vertices.
     *
     * This function takes a set of vertices and generates box projection UVs for each vertex.
     * The generated UVs are then stored in the vertices' TexCoord field.
     *
     * Box projection UVs are generated by taking the absolute value of the vertex normal and
     * then using the two largest components of the normal to generate a UV coordinate.
     * The UV coordinates are then normalized to the range [0, 1] to ensure proper UV mapping.
     *
     * @param vertices The set of vertices to generate box projection UVs for.
     */
    void GenerateBoxProjectionUVs(std::vector<Vertex>& vertices)
    {
        if (vertices.empty()) return;

        glm::vec2 minUV(FLT_MAX), maxUV(-FLT_MAX);
        std::vector<glm::vec2> projected(vertices.size());

        for (size_t i = 0; i < vertices.size(); ++i) 
        {
            const glm::vec3& pos = vertices[i].Position;
            glm::vec3 n = glm::abs(glm::normalize(vertices[i].Normal));
            glm::vec2 uv;
            if (n.x >= n.y && n.x >= n.z)       uv = { pos.y, pos.z }; // YZ
            else if (n.y >= n.x && n.y >= n.z)  uv = { pos.x, pos.z }; // XZ
            else                                uv = { pos.x, pos.y }; // XY

            projected[i] = uv;
            minUV = glm::vec2(std::min<float>(minUV.x, uv.x), std::min<float>(minUV.y, uv.y));
            maxUV = glm::vec2(std::max<float>(maxUV.x, uv.x), std::max<float>(maxUV.y, uv.y));
        }

        glm::vec2 uvDifference = maxUV - minUV;
        glm::vec2 range = glm::vec2(std::max<float>(uvDifference.x, 1e-5f), std::max<float>(uvDifference.y, 1e-5f));
        
        for (size_t i = 0; i < vertices.size(); ++i)
            vertices[i].TexCoord = (projected[i] - minUV) / range;
    }

    static void GenerateNormals(std::vector<Vertex>& vertices, const std::vector<uint32_t>& indices)
    {
        for (auto& v : vertices) v.Normal = glm::vec3(0.0f);

        for (size_t i = 0; i < indices.size(); i += 3)
        {
            uint32_t I0 = indices[i];
            uint32_t I1 = indices[i + 1];
            uint32_t I2 = indices[i + 2];

            glm::vec3& P0 = vertices[I0].Position;
            glm::vec3& P1 = vertices[I1].Position;
            glm::vec3& P2 = vertices[I2].Position;

            glm::vec3 E1 = P1 - P0;
            glm::vec3 E2 = P2 - P0;

            glm::vec3 faceNormal = glm::normalize(glm::cross(E1, E2));

            vertices[I0].Normal += faceNormal;
            vertices[I1].Normal += faceNormal;
            vertices[I2].Normal += faceNormal;
        }

        for (auto& v : vertices)
            v.Normal = glm::normalize(v.Normal);
    }

